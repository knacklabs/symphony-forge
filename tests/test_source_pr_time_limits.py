"""Forge's own pull request groups get forty-five minutes instead of thirty.

Test-audit gate:
1. Protect the Actions job limit generated by the real sync command for Forge.
2. A shared thirty-minute limit cancels Forge's full-suite pull request groups.
3. test_full_run_time_limits owns new and earlier-adopted client limits, not Forge's limit.
4. Read the generated workflow GitHub consumes. No production seam is needed.
"""
from test_testplace_workflow import _jobs

STORY = "FIX-FORGE-PR-GROUPS-45-MINUTES"


def test_1_forge_pr_groups_get_forty_five_minutes(repo):
    repo.git("checkout", "-qb", "fix/source-time-limit")
    version = repo.forge("--version").stdout.split()[-1]
    repo.write("forge.toml", f'version = "{version}"\nrepo = "forge-source"\n'
               'test = "python -m pytest tests -q"\nchecks = ["tests"]\ngroups = 2\n')

    synced = repo.forge("sync")

    assert synced.returncode == 0, synced.stdout + synced.stderr
    jobs = _jobs((repo.path / ".github/workflows/forge.yml").read_text(encoding="utf-8"))
    assert "group: [1, 2]" in jobs["tests"]
    assert "    timeout-minutes: 45\n" in jobs["tests"]
